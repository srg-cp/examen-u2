[CmdletBinding()]
param([string]$Plan = 'migration_plans/001_auth_profiles.json')

$ErrorActionPreference = 'Stop'
$databaseRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$repositoryRoot = Split-Path -Parent $databaseRoot
$planPath = [IO.Path]::GetFullPath((Join-Path $databaseRoot $Plan))
$rootPrefix = $databaseRoot + [IO.Path]::DirectorySeparatorChar
if (!$planPath.StartsWith($rootPrefix, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'El plan debe estar dentro de database.'
}
$manifest = Get-Content -LiteralPath $planPath -Raw | ConvertFrom-Json
if ([string]$manifest.version -notmatch '^\d{14}$' -or [string]$manifest.name -notmatch '^[a-z][a-z0-9_]+$') {
    throw 'Versión o nombre de migración inválidos.'
}
[void][DateTime]::ParseExact([string]$manifest.version, 'yyyyMMddHHmmss', [Globalization.CultureInfo]::InvariantCulture)
$categories = @('extensions', 'types', 'tables', 'indexes', 'functions', 'triggers', 'views', 'policies', 'grants')
$numbers = @{}
foreach ($category in $categories) {
    foreach ($sourceFile in Get-ChildItem -LiteralPath (Join-Path $databaseRoot $category) -Filter '*.sql' -File) {
        if ($sourceFile.Name -notmatch '^(\d{3,})_[a-z][a-z0-9_]*\.sql$') { throw "Nombre SQL inválido: $($sourceFile.Name)" }
        $number = [long]$Matches[1]
        if ($numbers.ContainsKey($number)) { throw "Número global duplicado: $number" }
        $numbers[$number] = $sourceFile.FullName
    }
}
$selected = foreach ($source in $manifest.sources) {
    $relativePath = [string]$source
    if (($relativePath -split '/')[0] -notin $categories) { throw 'Solo se permiten fuentes de esquema en el plan.' }
    $sourcePath = [IO.Path]::GetFullPath((Join-Path $databaseRoot $relativePath))
    if (!$sourcePath.StartsWith($rootPrefix, [StringComparison]::OrdinalIgnoreCase)) { throw 'Fuente fuera de database.' }
    $sourceFile = Get-Item -LiteralPath $sourcePath
    if ($sourceFile.Name -notmatch '^(\d{3,})_[a-z][a-z0-9_]*\.sql$') { throw 'Nombre SQL inválido.' }
    [pscustomobject]@{ Number = [long]$Matches[1]; RelativePath = $relativePath; Path = $sourcePath }
}
if (!$selected -or ($selected | Group-Object Number | Where-Object Count -gt 1)) {
    throw 'El plan está vacío o repite fuentes.'
}
$lines = New-Object 'System.Collections.Generic.List[string]'
$lines.Add('-- GENERATED by database/scripts/Build-Migration.ps1. Do not edit independently.')
$lines.Add('-- HU-01 / RF-01,34. Apply this entire migration once.')
$lines.Add('begin;')
foreach ($source in ($selected | Sort-Object Number)) {
    $sql = [IO.File]::ReadAllText($source.Path).Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd() + "`n"
    $hasher = [Security.Cryptography.SHA256]::Create()
    try { $hash = [BitConverter]::ToString($hasher.ComputeHash([Text.Encoding]::UTF8.GetBytes($sql))).Replace('-', '').ToLowerInvariant() }
    finally { $hasher.Dispose() }
    $lines.Add('')
    $lines.Add("-- Source: database/$($source.RelativePath) | normalized SHA256: $hash")
    $lines.Add($sql.TrimEnd())
}
$lines.Add('')
$lines.Add('commit;')
$content = ($lines -join "`n") + "`n"
$outputDirectory = Join-Path $repositoryRoot 'supabase/migrations'
$outputPath = Join-Path $outputDirectory "$($manifest.version)_$($manifest.name).sql"
if (Test-Path -LiteralPath $outputPath) {
    $existing = [IO.File]::ReadAllText($outputPath).Replace("`r`n", "`n")
    if ($existing -ne $content) { throw 'La migración ya existe con otro contenido. No reescribir el historial; usar un nuevo plan.' }
    Write-Output 'Migración comprobada: contenido idéntico a sus fuentes.'
    return
}
$null = New-Item -ItemType Directory -Path $outputDirectory -Force
[IO.File]::WriteAllText($outputPath, $content, (New-Object Text.UTF8Encoding($false)))
Write-Output "Migración generada: supabase/migrations/$($manifest.version)_$($manifest.name).sql"
