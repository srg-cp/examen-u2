import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { recoveryFixture, petId } from '../tests/recovery_fixture.mjs';
import { chooseDate, chooseTime } from './field-browser-helpers.mjs';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
const server = await recoveryFixture();
const output = new URL('../../mobile/build/ui-preview/web-fields/', import.meta.url);
await mkdir(output, { recursive: true });
try {
  const original = server.pets.get(petId);
  for (let i=0;i<10;i++) server.pets.set(`99999999-9999-4999-8999-${String(i).padStart(12,'0')}`, { ...original,id:`99999999-9999-4999-8999-${String(i).padStart(12,'0')}`,name:i === 9 ? 'Ámbar' : `Mascota ${i}` });
  const page = await browser.newPage({ viewport:{width:1440,height:1000},reducedMotion:'no-preference' });
  page.setDefaultTimeout(10000);
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(/Content Security Policy|Refused to|[Hh]ydration.*mismatch/.test(m.text()))errors.push(m.text());});
  await page.route('https://basemaps.cartocdn.com/**',r=>r.fulfill({status:200,contentType:'image/jpeg',body:server.jpeg}));
  await page.goto(server.origin+'/iniciar-sesion');
  await page.getByLabel('Correo',{exact:true}).fill('ordinario@example.test');
  await page.getByLabel('Contraseña',{exact:true}).fill('test-fixture-password');
  await page.getByLabel('Contraseña',{exact:true}).press('Enter');
  await page.waitForURL('**/inicio');
  console.log('Fields QA: signed in');
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  const holdSession = async route => { await gate; await route.continue(); };
  await page.route('**/api/access/session',holdSession);
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await page.evaluate(() => {
    window.fieldFrames=[];
    const tick=()=>{const el=document.querySelector('.sader-morph-panel');if(el)window.fieldFrames.push({width:el.getBoundingClientRect().width,transform:getComputedStyle(el).transform,blur:getComputedStyle(el.firstElementChild).filter});requestAnimationFrame(tick);};tick();
  });
  await page.locator('.user-navigation-report').click();
  try {
    await page.getByRole('progressbar',{name:'Cargando página'}).waitFor();
    assert.equal(await page.locator('.sader-top-loader').evaluate(el=>getComputedStyle(el,'::after').backgroundColor),'rgb(40, 135, 239)','Loading segment follows the sky-blue theme');
    await page.screenshot({path:fileURLToPath(new URL('top-loading-bar.png',output))});
  } finally { release(); }
  await page.waitForURL('**/reportar');
  await page.unroute('**/api/access/session',holdSession);
  await page.getByRole('progressbar',{name:'Cargando página'}).waitFor({state:'hidden'});
  const picker = page.getByRole('combobox',{name:'Tu mascota',exact:true});
  await picker.click();
  const search = page.getByRole('textbox',{name:'Buscar en Tu mascota',exact:true});
  await search.fill('ambar');
  assert.equal(await search.evaluate(el=>getComputedStyle(el).borderTopWidth),'0px','Search keeps the source borderless skin');
  const list=page.getByRole('listbox',{name:'Tu mascota',exact:true});
  assert.equal(await list.getByRole('option').count(),1);
  await page.waitForTimeout(500);
  await page.screenshot({path:fileURLToPath(new URL('select-search.png',output))});
  await search.press('Enter');
  await list.waitFor({state:'hidden'});
  assert.match(await picker.innerText(),/Ámbar/);
  assert.equal(await picker.evaluate(el=>el===document.activeElement),true);
  await picker.press('ArrowDown');
  await search.fill('ambar');
  const selectedOption = list.getByRole('option',{name:'Ámbar',exact:true});
  assert.deepEqual(await selectedOption.evaluate(el=>({background:getComputedStyle(el).backgroundColor,color:getComputedStyle(el).color})),{background:'rgb(214, 232, 255)',color:'rgb(36, 76, 117)'},'Selected options use the shared sky-blue pair');
  await search.press('Escape');
  await list.waitFor({state:'hidden'});
  assert.equal(await picker.evaluate(el=>el===document.activeElement),true);
  const frames=await page.evaluate(()=>window.fieldFrames);
  assert.ok(frames.some(f=>f.transform!=='none' && f.blur!=='blur(0px)'), 'Actual morph and content blur frames');
  await writeFile(new URL('frames.json',output),JSON.stringify(frames,null,2));
  console.log('Fields QA: morph, search, keyboard, focus');
  await chooseDate(page,'Fecha y hora · fecha','2026-10-19');
  await chooseTime(page,'Fecha y hora · hora','23:59');
  assert.match(await page.getByRole('button',{name:'Fecha y hora · hora',exact:true}).innerText(),/11:59 PM/);
  await page.getByRole('button',{name:'Fecha y hora · hora',exact:true}).click();
  await page.waitForTimeout(450);
  const timeDialog=page.getByRole('dialog',{name:'Fecha y hora · hora',exact:true});
  assert.equal(await timeDialog.locator('.selected').count(),2);
  assert.equal(await timeDialog.locator('.selected').first().evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(214, 232, 255)');
  await page.screenshot({path:fileURLToPath(new URL('time-theme.png',output))});
  await page.keyboard.press('Escape');await timeDialog.waitFor({state:'hidden'});
  const place=page.getByLabel('Referencia del lugar (privada)',{exact:true});
  await place.fill('Parque del barrio');
  await page.waitForTimeout(220);
  assert.equal(await place.locator('..').locator('.sader-text-outline').evaluate(el=>getComputedStyle(el).borderTopColor),'rgb(44, 135, 206)','Inputs use the shared blue notched outline');
  console.log('Fields QA: full-day time and local date');
  for (const width of [1920,1440,731,390,320]) {
    await page.setViewportSize({width,height:900});
    await page.getByRole('button',{name:'Fecha y hora · fecha',exact:true}).click();
    const dialog=page.getByRole('dialog',{name:'Fecha y hora · fecha',exact:true});
    await page.waitForTimeout(450);
    const rect=await dialog.boundingBox();assert.ok(rect.x>=7 && rect.x+rect.width<=width-7,'Calendar viewport bounds');
    assert.equal(await dialog.locator('.selected').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(214, 232, 255)','Calendar uses the same selected color');
    await page.screenshot({path:fileURLToPath(new URL(`calendar-${width}.png`,output))});
    await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.evaluate(()=>document.documentElement.style.fontSize='200%');
  await picker.click();
  assert.equal(await page.locator('.sader-morph-panel').evaluate(el=>el.getAnimations().length),0);
  await page.screenshot({path:fileURLToPath(new URL('select-320-text200.png',output))});
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  console.log('Fields Chrome QA passed: animation frames, search, keyboard, focus, full-day time, 1920/1440/731/390/320, text200%, reduced motion, no CSP/hydration errors.');
} finally { await browser.close(); await server.close(); }
